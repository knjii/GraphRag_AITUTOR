#!/usr/bin/env bash
# Сессия 2026-08-23. Отладка, честная точка отсчёта по ответам, разбор
# причин потери формул, точность графового канала.
#
#   bash deploy/session-0823.sh          всё подряд
#   bash deploy/session-0823.sh 0        только отладка
#   bash deploy/session-0823.sh 1        только замер ответов
#
# Блоки идут строго по порядку, и блок 0 обрывает сессию при неудаче.
# Причина не в аккуратности, а в опыте: прогон 2026-08-19 отработал целиком
# и дал правдоподобные числа, посчитанные по потоку размышлений модели.
# Дешевле остановиться на первой минуте, чем разбирать это потом три дня.

set -uo pipefail
cd "${REPO_DIR:-$HOME/rag_textbook}" || exit 1
export PATH="$HOME/.local/bin:$PATH"

BLOCK="${1:-all}"
say()   { printf '\n\033[1;34m=== %s ===\033[0m\n' "$*"; }
die()   { printf '\n\033[1;31mОСТАНОВ: %s\033[0m\n' "$*" >&2; exit 1; }
clean() { grep -v -E ' INFO | WARNING |pymorphy|neo4j\.notifications'; }
run()   { [ "$BLOCK" = "all" ] || [ "$BLOCK" = "$1" ]; }

# .env правится по ключам: там лежат тексты промптов с пробелами и кавычками,
# и исполнение файла как кода shell их ломает.
set_key() {
    if grep -q "^$1=" .env; then sed -i "s|^$1=.*|$1=$2|" .env
    else printf '%s=%s\n' "$1" "$2" >> .env; fi
}

# ---------------------------------------------------------------- блок 0
if run 0; then

say "Блок 0.1. Настройки под новое окно"
# Длина контекста движка обязана быть не меньше нашей: бюджет символов
# считаем мы, а отвергает запрос движок. Расхождение выглядит как ошибка 400
# на длинных промптах где-то посреди замера.
set_key SGLANG_MAX_MODEL_LEN 16384
set_key LLM_CONTEXT_WINDOW 16384
set_key LLM_CHAT_REASONING_EFFORT none
set_key PROMPT_VERSION v3
set_key CONTEXT_ORDER relevance
set_key FORMULA_BUDGET_SHARE 1.6
set_key CONTEXT_WINDOW_SHARE 0.5
set_key RETRIEVAL_ROUTER_MODE always
set_key RETRIEVAL_TOP_K 16
grep -E '^(SGLANG_MAX_MODEL_LEN|LLM_CONTEXT_WINDOW|LLM_CHAT_REASONING_EFFORT|PROMPT_VERSION|CONTEXT_ORDER|FORMULA_BUDGET_SHARE|CONTEXT_WINDOW_SHARE|RETRIEVAL_ROUTER_MODE|RETRIEVAL_TOP_K)=' .env | sort

say "Блок 0.2. Перезапускаю движок с длиной 16384"
# Удвоение длины при той же доле памяти примерно вдвое сокращает число
# одновременных слотов. Если пропускная способность просядет — уменьшать
# LLM_MAX_CONCURRENCY, а не длину: длина здесь и есть предмет проверки.
COMPOSE="docker compose --env-file $PWD/.env -f $PWD/docker/docker-compose.vllm.yml"
$COMPOSE --profile sglang up -d --force-recreate sglang || die "SGLang не поднялся"
printf '    жду готовности'
for _ in $(seq 1 60); do
    curl -sf -o /dev/null http://127.0.0.1:8001/health && { printf ' готов\n'; break; }
    printf '.'; sleep 10
done
curl -sf -o /dev/null http://127.0.0.1:8001/health || die "движок не поднялся за 10 минут"
nvidia-smi --query-gpu=memory.used,memory.total --format=csv,noheader

say "Блок 0.3. Связность и три рубежа"
# health теперь проверяет не только доступность: длину контекста движка
# против нашей, размышление вместо ответа и язык ответа.
uv run rag-textbook health 2>&1 | clean || die "health не прошёл — читайте строку llm в таблице"

say "Блок 0.4. Граф: сверка с состоянием до затирания"
# Было 1151 passages / 4059 entities. После пересборки из кэша стало
# 1151 / 3836 — расхождение 5.5% при том, что пересборка модель не вызывает
# и обязана быть повторяемой. Либо кэш неполон, либо сборка недетерминирована;
# и то и другое надо знать до того, как мерить граф.
uv run rag-textbook graph stats 2>&1 | clean | tail -14

say "Блок 0.5. Сверка поиска с известным числом"
# recall@16 обязан воспроизвести 0.854. Не сошлось — окружение поехало,
# и всё дальнейшее сравнивать не с чем.
uv run rag-textbook eval run --label sanity 2>&1 | clean | tail -24

say "Блок 0.6. Пять ответов глазами"
# Единственная проверка, которую нельзя заменить метрикой: прочитать текст.
for q in \
    "Что такое собственное значение матрицы?" \
    "Приведи формулу плотности нормального распределения" \
    "Как связаны определитель и собственные значения?" \
    "Что такое условная вероятность?" \
    "Приведи неравенство Коши-Буняковского"; do
    printf '\n\033[1;36m--- %s\033[0m\n' "$q"
    uv run rag-textbook ask "$q" 2>&1 | clean | head -24
done

cat <<'CHECK'

    ЧТО ПРОВЕРИТЬ ГЛАЗАМИ, прежде чем идти дальше:
      * ни одного тега think и ни одного «The user is asking»;
      * ответ по-русски целиком;
      * формула перенесена в LaTeX и совпадает с источником, а не пересказана;
      * ссылки вида [1] есть, и страницы в них не «p.?».

    Хоть один пункт не выполнен — останавливаемся и чиним. Замер по таким
    ответам уже был, он стоил трёх дней разбора.
CHECK
fi

# ---------------------------------------------------------------- блок 1
if run 1; then

say "Блок 1. Честная точка отсчёта по ответам, 388 вопросов"
# Без судьи намеренно. Судьёй работает та же модель, что и отвечает, и
# в прошлом прогоне она ставила размышлению 1.781, а тексту без него 0.116.
# Без неё остаются величины, которым можно верить: сохранность формул,
# опора на контекст, доля размышлений, отказы.
uv run rag-textbook eval answers --no-judge --label baseline-fixed 2>&1 | clean | tail -26

# Критерий проверяется, а не печатается. В первом варианте скрипт выводил
# «Не выполнено — блоки 2 и 3 бессмысленны» всегда, независимо от чисел:
# напоминание выглядело приговором. Ровно тот род ошибки, который мы ловим
# в метриках, — видимость проверки вместо проверки.
LEAK=$(uv run python -c "
import json,glob
f=sorted(glob.glob('artifacts/metrics/answers_baseline-fixed*.json'))[-1]
s=json.load(open(f,encoding='utf-8'))['summary']['всего']
print(s.get('размышление вместо ответа',1.0))
" 2>/dev/null)
echo
echo "    КРИТЕРИЙ ПРИЁМКИ: размышлений меньше 0.02 (было 0.60), получено $LEAK"
awk -v v="$LEAK" 'BEGIN{ if (v+0 < 0.02) print "    ПРОЙДЕН"; else print "    НЕ ПРОЙДЕН: метрики снова не про ответы, блоки 2 и 3 бессмысленны" }'
fi

# ---------------------------------------------------------------- блок 2
if run 2; then

say "Блок 2. Чья вина в потере формул: окно или промпт"
# Четыре ячейки 2x2. Контекст берётся из слепка, поиск не выполняется:
# значит, между ячейками меняется ровно одно, и сравнение честное.
# Движок остаётся на 16384 — «малое окно» задаётся нашей стороной, потому
# что бюджет символов считаем мы. Перезапускать движок не нужно.
# Слепок берём тот, что снят на принятой конфигурации: маршрут всегда в граф,
# выдача 16. Слепок capture/trace.jsonl снят при выдаче 8 и для этого блока
# не годится — обрезка формул возникает именно на 16 фрагментах, а при 8
# бюджета хватало на 99.8% чанков, и мерить было бы нечего.
TRACE=capture/session-0819/trace-always.jsonl
[ -f "$TRACE" ] || die "нет $TRACE — слепок нужен для этого блока"
[ -f deploy/prompts/qa-v2.txt ] || die "нет текста прежнего промпта — сравнивать не с чем"

# Ловушка, на которую я едва не наступил: PROMPT_VERSION меняет только ярлык
# в отпечатке, а не текст. Задай я одну эту переменную — обе ячейки прогнали бы
# один и тот же промпт, а разница в числах читалась бы как эффект правки.
# Поэтому прежний текст подаётся явно, из файла.
PROMPT_V2="$(cat deploy/prompts/qa-v2.txt)"

for window in 8192 16384; do
    for version in v2 v3; do
        say "окно $window, промпт $version"
        if [ "$version" = "v2" ]; then
            PROMPT_ENV=(QA_SYSTEM_PROMPT="$PROMPT_V2" PROMPT_VERSION=v2)
        else
            # v3 — значение по умолчанию в коде, подставлять нечего.
            PROMPT_ENV=(PROMPT_VERSION=v3)
        fi
        env "${PROMPT_ENV[@]}" LLM_CONTEXT_WINDOW=$window \
            uv run rag-textbook eval answers \
                --from-trace "$TRACE" --no-judge \
                --label "cell-${window}-${version}" 2>&1 | clean | tail -18
    done
done

say "Отпечатки промптов по ячейкам — они обязаны различаться"
# Если отпечатки v2 и v3 совпали, сравнение было пустым, и числа ничего
# не значат. Проверяется по сохранённым файлам, а не на глаз.
grep -h '"промпт"' artifacts/metrics/answers_cell-*.json | sort -u

cat <<'CHECK'

    ЧТО ЧИТАТЬ: «формулы дошли» по четырём ячейкам.

    Критерий отказа для промпта назван заранее: если v3 при том же окне
    не удвоил сохранность формул — дело не в инструкции.
    Критерий для окна такой же: если 16384 при том же промпте не дал
    прироста — окно не было узким местом, и остаётся гипотеза B2, размер
    модели.
CHECK
fi

# ---------------------------------------------------------------- блок 3
if run 3; then

say "Блок 3. Точность графового канала"
# Доступ уже измерен и узким местом не является: граф занимает медианно
# три места из восьми, а исключительно графовых среди них 0.21 на вопрос.
# Значит, бить надо в точность канала, а не в его ширину. Порог хабов —
# главный рычаг из измеренных: понятие, встречающееся всюду, связывает
# всё со всем и наполняет канал шумом.
for degree in 24 40 64; do
    say "порог хабов $degree"
    GRAPH_MAX_ENTITY_DEGREE=$degree \
        uv run rag-textbook eval run --label "hub-$degree" 2>&1 | clean | tail -20
done

say "Обратная величина частоты для отрывков выключена"
GRAPH_PASSAGE_IDF_ENABLED=false \
    uv run rag-textbook eval run --label idf-off 2>&1 | clean | tail -20

cat <<'CHECK'

    ЧТО ЧИТАТЬ: recall@16 и строку «Граф: … нашёл N% контекста, из них
    только он — M%». Растёт M при том же recall — канал стал точнее.
    Падает recall — порог срезал нужное, направление закрыто.
CHECK
fi

say "СЕССИЯ_ЗАВЕРШЕНА"
ls -la artifacts/metrics/ | tail -20
