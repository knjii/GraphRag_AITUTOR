#!/usr/bin/env bash
# Фаза 1: снять слепок и уехать. Экспериментов здесь нет намеренно.
#
#   bash deploy/capture.sh
#
# Прошлая серверная сессия ушла на семь проверок, из которых не подтвердилась
# ни одна — соблазн «раз уж подняли, проверим ещё одну» обходится дороже, чем
# кажется. Эта сессия ровно на снятие данных: после неё весь перебор порядка
# и отбора считается офлайн бесплатно.
#
# Что снимается:
#   1. точка отсчёта — сверить, что окружение не поехало;
#   2. слепок поиска — кандидаты каналов, баллы реранкера по широкому окну,
#      итоговый отбор по каждому вопросу;
#   3. эталонный набор и фрагменты — офлайн-перебору нужны их тексты;
#   4. журнал отказов извлечения — причина, по которой 37 фрагментов уходят
#      в правиловый откат, до сих пор нигде не записана.

set -uo pipefail
cd "${REPO_DIR:-$HOME/rag_textbook}" || exit 1
export PATH="$HOME/.local/bin:$PATH"

OUT="$HOME/capture-$(date +%Y%m%d-%H%M)"
mkdir -p "$OUT"

say()  { printf '\n\033[1;34m=== %s ===\033[0m\n' "$*"; }
ok()   { printf '\033[1;32m    %s\033[0m\n' "$*"; }
warn() { printf '\033[1;33m    %s\033[0m\n' "$*"; }
die()  { printf '\033[1;31m    %s\033[0m\n' "$*" >&2; exit 1; }

clean() { grep -v -E ' INFO | WARNING |pymorphy|neo4j\.notifications'; }

say "Проверяю службы"
uv run rag-textbook health 2>&1 | clean | tail -20

say "Точка отсчёта"
# Если число разойдётся с 0.754, окружение поехало, и снимать слепок незачем:
# офлайн-перебор будет опираться на данные другой системы.
uv run rag-textbook eval run --label baseline-388 2>&1 | clean | tail -25

say "Снимаю слепок"
# Расширяется ОЦЕНИВАНИЕ, а не отбор. Расширить пул отбора значило бы снять
# слепок с другой конфигурации, и сверка честности не сошлась бы — проверено:
# первая попытка дала 32% точных совпадений именно из-за этого. Баллы
# кросс-энкодера считаются попарно и от состава пакета не зависят, поэтому
# оценить можно шире, чем отобрать.
EVAL_TRACE_POOL=100 EVAL_TRACE_RERANK_ALL=1 \
    uv run rag-textbook eval run --label trace-388 --trace "$OUT/trace.jsonl" \
    2>&1 | clean | tail -25

[ -s "$OUT/trace.jsonl" ] || die "слепок пуст — офлайн-фаза без него невозможна"
ok "строк в слепке: $(wc -l < "$OUT/trace.jsonl")"

say "Собираю всё, что нужно офлайну"
cp evaluation/goldsets/goldset.json "$OUT/goldset.json"
cp artifacts/parsed/*_chunks.json "$OUT/" 2>/dev/null || warn "фрагменты не найдены"
cp artifacts/state/extraction_failures.jsonl "$OUT/" 2>/dev/null \
    || warn "журнал отказов пуст: он заполнится при следующей пересборке графа"
cp -r artifacts/metrics "$OUT/metrics" 2>/dev/null

say "Выгрузка графа"
# Граф нужен офлайну не для обхода — обход слепком не проверяется, — а чтобы
# читать глазами связи вокруг промахов.
uv run rag-textbook graph stats 2>&1 | clean | tail -12 > "$OUT/graph-stats.txt"
cat "$OUT/graph-stats.txt"

say "Готово"
du -sh "$OUT"
ls -la "$OUT"
cat <<NOTE

    Забрать на ноутбук:
      scp -r root@СЕРВЕР:$OUT ./capture

    Дальше офлайн, аренда больше не нужна:
      uv run rag-textbook eval replay capture/trace.jsonl

    Первое, что напечатает replay, — сверка честности. Пока она не сойдётся,
    к перебору не переходить: расхождение означает, что слепок неполон,
    и любые выводы по нему будут про другую систему.
NOTE
