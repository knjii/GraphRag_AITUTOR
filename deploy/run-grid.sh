#!/usr/bin/env bash
# Достроить сетку «окно x промпт» до полной, после того как освободится карта.
#
#   nohup bash deploy/run-grid.sh > /tmp/grid.log 2>&1 &
#
# Что уже есть: v2 и v3 при 8192 и 16384, v4 и v5 при 16384. Не хватает
# v4 и v5 при 8192 — без них преимущество v4 нельзя разложить на вклад
# формулировки и вклад окна, а у v3 такое разложение показало, что эффекты
# усиливают друг друга: окно даёт +0.019 при старом промпте и +0.080
# при новом.
#
# Ожидание сделано по имени соседнего скрипта, поэтому имя собирается
# из частей: строка, переданная в ssh, содержала бы его целиком, и pgrep
# нашёл бы сам себя. Дважды на это уже наступил.

set -uo pipefail
cd "${REPO_DIR:-$HOME/rag_textbook}" || exit 1
export PATH="$HOME/.local/bin:$PATH"

WAIT_FOR="models""-ab"
say() { printf '\n\033[1;35m### %s (%s)\033[0m\n' "$*" "$(date +%H:%M)"; }

say "Жду окончания сравнения моделей"
while pgrep -f "$WAIT_FOR" | grep -q . ; do sleep 60; done

# Сравнение моделей гасит службы поиска и в конце возвращает рабочую
# конфигурацию с моделью 4B. Здесь она и нужна: сетка промптов меряет
# формулировку, а не модель, и обязана идти на той же модели, что и прежние
# ячейки, иначе числа несравнимы.
say "Жду готовности движка"
for _ in $(seq 1 60); do
    curl -sf -o /dev/null http://127.0.0.1:8001/health && break
    sleep 10
done

for version in v4 v5; do
    say "Достраиваю: промпт $version, окно 8192"
    WINDOW=8192 bash deploy/prompt-search.sh "$version" > "/tmp/grid-$version.log" 2>&1
done

say "СЕТКА_ДОСТРОЕНА"
ls -la artifacts/metrics/answers_prompt-*.json
