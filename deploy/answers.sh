#!/usr/bin/env bash
# Замер качества ОТВЕТОВ. Первый в проекте: все прежние метрики были про поиск.
#
#   bash deploy/answers.sh
#
# Порядок прогонов выбран так, чтобы каждое число можно было прочесть.
#
#   1. Проверенная выборка. Только вопросы, вычитанные человеком: на них
#      числа означают то, что написано. Их мало, поэтому доверительный
#      интервал широк — зато нет спора о том, что мерили.
#   2. Весь набор. Числа шумнее по смыслу (половина связывающих вопросов
#      отвечается одним фрагментом), зато это точка отсчёта для сравнения
#      будущих конфигураций между собой.
#   3. Без судьи, весь набор. Остаются только объективные величины —
#      сохранность формул и доля выдумки. Их можно предъявлять как есть.

set -uo pipefail
cd "${REPO_DIR:-$HOME/rag_textbook}" || exit 1
export PATH="$HOME/.local/bin:$PATH"

say()  { printf '\n\033[1;34m=== %s ===\033[0m\n' "$*"; }
clean() { grep -v -E ' INFO | WARNING |pymorphy|neo4j\.notifications'; }

say "Переношу вердикты ручной проверки"
# Без этого --verified-only не найдёт ни одного вопроса.
uv run rag-textbook goldset verdicts --apply 2>&1 | clean | tail -12

say "Проверенная выборка, с судьёй"
uv run rag-textbook eval answers --verified-only --label verified 2>&1 | clean | tail -20

say "Весь набор, с судьёй"
uv run rag-textbook eval answers --label full 2>&1 | clean | tail -20

say "Весь набор, только объективные величины"
uv run rag-textbook eval answers --no-judge --label objective 2>&1 | clean | tail -18

say "Готово"
ls -la artifacts/metrics/answers_*.json
cat <<'NOTE'

    Что читать в первую очередь: «формулы дошли» и «выдумка». Они не зависят
    ни от модели-судьи, ни от разметки набора.

    «Верность» и «обоснованность» считает та же модель, что и отвечает.
    Она склонна одобрять собственные ответы, поэтому годятся они для
    сравнения конфигураций между собой, а не как оценка качества продукта.
NOTE
