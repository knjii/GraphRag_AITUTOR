#!/usr/bin/env bash
# Подбор промпта генератора по замороженному контексту.
#
#   bash deploy/prompt-search.sh            все варианты
#   bash deploy/prompt-search.sh v4         один
#
# Почему по слепку. Поиск не выполняется, контекст у всех вариантов один
# и тот же, поэтому разница относится к формулировке промпта, а не к тому,
# что кому досталось при поиске. Прогон одного варианта — около десяти минут
# и нисколько аренды сверх той, что уже оплачена.
#
# Варианты и чем они отличаются:
#
#   v2  «Формулы приводи в LaTeX» — то, с чем шли все прежние замеры.
#       Говорит про ФОРМАТ записи и не запрещает пересказ.
#   v3  «Переноси дословно, пересказ запрещён» — принято 2026-09-03,
#       удвоило сохранность формул (0.033 → 0.074).
#   v4  v3 плюс порядок ответа (сначала формула, потом пояснение),
#       сохранение номера формулы и явный запрет служебных строк.
#       Последнее — по наблюдению: в одном ответе из пяти модель
#       приписывала «Переформулированный вопрос: …».
#   v5  v3 плюс показанный пример верного и неверного ответа.
#       Проверяет, работает ли показ лучше запрета.
#
# Мерять надо величину «хотя бы одна формула эталона дошла», а не долю:
# доля требует, чтобы в ответ попали ВСЕ формулы страницы, а хороший ответ
# приводит ту, о которой спрашивали.

set -uo pipefail
cd "${REPO_DIR:-$HOME/rag_textbook}" || exit 1
export PATH="$HOME/.local/bin:$PATH"

ONLY="${1:-all}"
# Окно задаётся снаружи, чтобы достроить сетку «окно x промпт» целиком.
# Движок при этом не трогаем: он держит 16384, а «малое окно» задаётся
# нашей стороной — бюджет символов считаем мы, и перезапуск не нужен.
WINDOW="${WINDOW:-16384}"
TRACE=capture/session-0819/trace-always.jsonl

say()   { printf '\n\033[1;34m=== %s ===\033[0m\n' "$*"; }
die()   { printf '\n\033[1;31mОСТАНОВ: %s\033[0m\n' "$*" >&2; exit 1; }
clean() { grep -v -E ' INFO | WARNING |pymorphy|neo4j\.notifications'; }

[ -f "$TRACE" ] || die "нет слепка $TRACE"

cell() {
    local version="$1"
    if [ "$ONLY" != "all" ] && [ "$ONLY" != "$version" ]; then return 0; fi
    local file="deploy/prompts/qa-${version}.txt"
    [ -f "$file" ] || die "нет файла промпта $file"

    say "промпт $version, окно $WINDOW"
    # Текст подаётся явно. PROMPT_VERSION меняет только ярлык в отпечатке,
    # и задай мы одну эту переменную — все варианты прогнали бы один и тот же
    # промпт, а разница в числах читалась бы как эффект правки.
    env QA_SYSTEM_PROMPT="$(cat "$file")" PROMPT_VERSION="$version" \
        LLM_CONTEXT_WINDOW="$WINDOW" \
        uv run rag-textbook eval answers \
            --from-trace "$TRACE" --no-judge \
            --label "prompt-${version}-w${WINDOW}" 2>&1 | clean | tail -20
}

for version in v2 v3 v4 v5; do
    cell "$version"
done

say "Отпечатки промптов — обязаны различаться"
grep -h '"промпт"' artifacts/metrics/answers_prompt-*.json | sort -u

cat <<'NOTE'

    Числа пересчитываются офлайн: scripts/recompute_answers.py
    Так все варианты меряются одной и той же версией измерителя, даже
    если он чинился между прогонами, — а он чинился трижды.
NOTE
