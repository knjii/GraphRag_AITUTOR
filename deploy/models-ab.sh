#!/usr/bin/env bash
# Сравнение генераторов по замороженному контексту. Гипотеза B2.
#
#   bash deploy/models-ab.sh                     все ячейки, окно 16384
#   WINDOW=8192 bash deploy/models-ab.sh         второй проход
#   bash deploy/models-ab.sh qwen27b             одна ячейка
#
# Устройство опыта.
#
# Поиск не выполняется вовсе: контекст берётся из слепка, все модели
# отвечают по одному и тому же материалу. Отсюда два следствия. Разница
# в числах относится к генератору, а не к тому, что кому досталось при
# поиске. И службы поиска можно погасить — их память нужна модели,
# а без 4 ГБ Infinity 30B в карту не помещается.
#
# ДВИЖОК ОДИН НА ВСЕ ЯЧЕЙКИ, и это вынужденное, но правильное решение.
# SGLang в нашем образе не поднимает эти модели вовсе: «GGUF model with
# architecture qwen35 is not supported yet» — образ старше моделей, о чём
# и предупреждало записанное правило. llama.cpp поднимает их все, а заодно
# снимает вопрос «движок или квантование»: будь часть ячеек на одном
# движке, а часть на другом, разницу нельзя было бы отнести ни к чему.
#
# Ячейки, в каждой паре меняется одно:
#
#   qwen4b   нынешний размер, точка отсчёта
#   qwen9b   вдвое больше, то же семейство, тот же квант
#   gemma12b другое семейство, обучена с учётом квантования
#   muse30b  Meta, плотная 30B со зрительным кодировщиком
#   qwen27b  вшестеро больше точки отсчёта, семейство и квант те же
#
# Чистые пары: (qwen4b, qwen9b), (qwen9b, qwen27b) — семейство и квант
# постоянны, меняется размер. Gemma и Muse сравниваются поперёк семейств:
# там разом меняются обучение, способ квантования и архитектура. Это
# читается как наблюдение, не как измерение.
#
# Цена самого квантования меряется отдельно: ячейки qwen4b-bf16
# и qwen9b-bf16 сняты на SGLang в первом проходе. Сравнение с ними несёт
# в себе и смену движка — оговорено прямо, а не замолчано.

set -uo pipefail
cd "${REPO_DIR:-$HOME/rag_textbook}" || exit 1
export PATH="$HOME/.local/bin:$PATH"

ONLY="${1:-all}"

# Окно контекста. Замеры обязаны быть симметричными: если модель проверена
# при 8192, она проверяется и при 16384. Это не педантизм — гипотеза B2
# говорит, что маленькие модели хуже используют длинный контекст, а значит
# прирост от окна обязан расти с размером модели. При одном окне такая
# зависимость невидима.
#
# Движок держит длинные слоты в обоих проходах: «малое окно» задаётся нашей
# стороной, потому что бюджет символов считаем мы, и перезапускать модель
# между проходами не нужно.
WINDOW="${WINDOW:-16384}"

# Промпт задаётся файлом, а не переменной версии: PROMPT_VERSION меняет
# только ярлык в отпечатке. Сюда передаётся победитель подбора промпта,
# чтобы модели сравнивались на лучшей известной формулировке.
PROMPT_FILE="${PROMPT_FILE:-deploy/prompts/qa-v4.txt}"
PROMPT_TAG="${PROMPT_TAG:-$(basename "$PROMPT_FILE" .txt | sed s/qa-//)}"

SERVICES="docker compose --env-file $PWD/.env -f $PWD/docker/docker-compose.yml"
TRACE=capture/session-0819/trace-always.jsonl
IMAGE=ghcr.io/ggml-org/llama.cpp:server-cuda
VOLUME=$(docker volume inspect rag-textbook_gguf_models --format '{{.Mountpoint}}')

# Размышление гасим везде: продукту нужен мгновенный ответ, а не цепочка
# рассуждений. Перебор ключей на Muse Glimmer 2026-09-04 (журнал пробы
# в deploy/probe-reasoning.sh) дал такую картину на одном вопросе:
#
#   без ключей                     119 токенов, рассуждение 472 знака
#   --reasoning off                119 токенов, 472 — НЕ ДЕЙСТВУЕТ
#   --reasoning-budget 0           119 токенов, 472 — НЕ ДЕЙСТВУЕТ
#   kwargs reasoning_effort=low     71 токен,   277
#   --reasoning-effort minimal      64 токена,  231  <- лучшее
#
# То есть у Muse рассуждение встроено в шаблон и полностью не гасится —
# только сокращается вдвое. Для продукта это довод против неё.
# У моделей, которые не рассуждают, ключ ничего не меняет, поэтому он
# ставится всем одинаково: настройка обязана быть общей, иначе ячейки
# несравнимы.
#
# Второй рубеж — предел ответа LLM_MAX_TOKENS=2048 вместо 768. У Muse
# лимит кончался ВНУТРИ рассуждения, и до ответа дело не доходило:
# 325 пустых ответов из 388. Ключ передаётся всем моделям одинаково,
# иначе ячейки несравнимы.
#
# Число слотов подбирается под размер модели, и это компромисс.
# От слотов зависит и пропускная способность, и объём кэша: шесть слотов
# по 16384 токена мелкая модель держит свободно, а 27-30B в четырёх битах
# уже нет — весов 17 ГБ, и на кэш остаётся около пяти.
#
# Задержку между моделями поэтому сравниваем ОСТОРОЖНО: у крупных ячеек
# очередь длиннее не только из-за модели, но и из-за числа слотов.
# Величина, которую сравниваем без оговорок, — сохранность формул:
# она от числа слотов не зависит вовсе.
SLOT_TOKENS=16384
slots_for() {
    case "$1" in
        muse30b|qwen27b) printf 2 ;;
        *)               printf 6 ;;
    esac
}

say()   { printf '\n\033[1;34m=== %s ===\033[0m\n' "$*"; }
warn()  { printf '\033[1;33m    %s\033[0m\n' "$*"; }
die()   { printf '\n\033[1;31mОСТАНОВ: %s\033[0m\n' "$*" >&2; exit 1; }
clean() { grep -v -E ' INFO | WARNING |pymorphy|neo4j\.notifications'; }
vram()  { nvidia-smi --query-gpu=memory.used,memory.total --format=csv,noheader; }

[ -f "$TRACE" ] || die "нет слепка $TRACE"
[ -f "$PROMPT_FILE" ] || die "нет файла промпта $PROMPT_FILE"

say "Промпт: $PROMPT_FILE (ярлык $PROMPT_TAG), окно $WINDOW"

say "Гашу службы поиска — их память нужна модели"
# Qdrant и Neo4j остаются: они на процессоре и видеопамяти не занимают.
$SERVICES stop infinity ollama >/dev/null 2>&1
# SGLang тоже: два движка на одной карте не помещаются.
docker rm -f rag-textbook-sglang-1 >/dev/null 2>&1
say "Свободно на карте: $(vram)"

# Файл ищется на хосте, движку отдаётся путь внутри контейнера: каталога
# /models на хосте нет. Берётся первый по алфавиту — у разделённых на части
# сборок это как раз часть 00001, с которой llama.cpp подхватывает остальные.
gguf_path() {
    local name
    name=$(find "$VOLUME/$1" -name "*.gguf" -printf '%f\n' 2>/dev/null | sort | head -1)
    [ -n "$name" ] || return 1
    printf '/models/%s/%s' "$1" "$name"
}

# Одна ячейка: поднять модель, дождаться, замерить, остановить.
# Модели поднимаются строго по очереди. Соблазн запустить две сразу,
# чтобы сэкономить время, кончится нехваткой памяти посреди прогона —
# так уже было с MinerU и SGLang.
cell() {
    local label="$1" dir="$2"
    if [ "$ONLY" != "all" ] && [ "$ONLY" != "$label" ]; then return 0; fi

    # Уже посчитанную ячейку не переделываем: очередь длинная, и её
    # приходится перезапускать — повтор того же стоил бы получаса.
    local out="artifacts/metrics/answers_model-${label}-w${WINDOW}.json"
    if [ -e "$out" ]; then
        say "Ячейка $label при окне $WINDOW уже посчитана, пропускаю"
        return 0
    fi

    local path slots
    path=$(gguf_path "$dir") || { warn "$label: файла нет, пропускаю"; return 0; }
    slots=$(slots_for "$label")

    say "Ячейка $label: $path (слотов $slots)"
    docker rm -f generator >/dev/null 2>&1
    docker run -d --name generator --gpus all \
        -v rag-textbook_gguf_models:/models \
        -p 127.0.0.1:8001:8000 \
        "$IMAGE" \
        -m "$path" --host 0.0.0.0 --port 8000 \
        -c $((SLOT_TOKENS * slots)) -np "$slots" -ngl 999 --jinja \
        --reasoning off --reasoning-effort minimal \
        >/dev/null || { warn "$label: контейнер не запустился"; return 0; }

    printf '    жду готовности'
    local ready=0
    for _ in $(seq 1 90); do
        curl -sf -o /dev/null http://127.0.0.1:8001/health && { ready=1; printf ' готов\n'; break; }
        printf '.'; sleep 10
    done
    if [ "$ready" = "0" ]; then
        printf '\n'
        warn "$label не поднялся за 15 минут, вот хвост журнала:"
        docker logs --tail 25 generator 2>&1 | tail -25
        docker rm -f generator >/dev/null 2>&1
        return 0
    fi
    say "Память под нагрузкой: $(vram)"

    # Прочитать три ответа, прежде чем тратить на модель полтора часа.
    # Правило куплено дорого: ячейка Muse Glimmer считалась полтора часа
    # и оказалась пустой — 325 ответов из 388 пустота, потому что модель
    # рассуждала и размышление съедало лимит токенов. Это было видно
    # на первом же ответе.
    say "Проверяю три ответа глазами и правилами"
    # Код возврата берётся у самой проверки, а не у фильтра логов: в связке
    # «команда | grep» оболочка вернула бы код grep, и негодная модель прошла
    # бы дальше. Поэтому вывод пишется в файл, а код читается отдельно.
    local smoke=/tmp/smoke-$label-$WINDOW.log
    uv run python scripts/smoke_generation.py --count 3 > "$smoke" 2>&1
    local smoke_code=$?
    clean < "$smoke" | tail -40
    if [ "$smoke_code" != "0" ]; then
        warn "$label: ответы негодны, ячейка пропущена — чинить и запускать заново"
        docker rm -f generator >/dev/null 2>&1
        return 0
    fi

    # Замер без судьи. Судьёй здесь работала бы одна из сравниваемых моделей,
    # а модель склонна одобрять свои ответы: в прогоне 2026-08-19 она ставила
    # размышлению 1.781 против 0.116 за текст без него. Остаются величины,
    # которым можно верить: сохранность формул, опора на контекст, доля
    # размышлений, язык, задержка.
    env QA_SYSTEM_PROMPT="$(cat "$PROMPT_FILE")" PROMPT_VERSION="$PROMPT_TAG" \
        LLM_CONTEXT_WINDOW="$WINDOW" \
        uv run rag-textbook eval answers \
            --from-trace "$TRACE" --no-judge \
            --label "model-${label}-w${WINDOW}" 2>&1 | clean | tail -24

    docker rm -f generator >/dev/null 2>&1
}

# Окно 8192 из опыта исключено: на продукте оно не используется, а платить
# за симметрию ради нерабочей настройки незачем. Все ячейки идут при 16384.
# Порядок: сначала дешёвые ячейки, затем дорогие. Muse последняя намеренно —
# она единственная, которую нельзя сделать быстрой, и если её придётся
# бросить, это уже ничего не задержит.
cell qwen4b   qwen4b
cell qwen9b   qwen9b
cell gemma12b gemma-12b
cell qwen27b  qwen27b
# Muse Glimmer отложена: рассуждение встроено в её шаблон и ключами
# движка не гасится, только сокращается вдвое. Ячейка стоит два-три
# часа против сорока минут у прочих, а модель с таким временем ответа
# в продукт всё равно не пойдёт. Вернуть строку, когда найдём способ
# выключить рассуждение полностью.
# cell muse30b  muse-30b

say "Возвращаю рабочую конфигурацию"
docker rm -f generator >/dev/null 2>&1
docker compose --env-file "$PWD/.env" -f "$PWD/docker/docker-compose.vllm.yml" \
    --profile sglang up -d sglang >/dev/null 2>&1
bash deploy/services.sh up 2>&1 | tail -4

say "Сводка по ячейкам, окно $WINDOW"
for file in artifacts/metrics/answers_model-*-w${WINDOW}.json; do
    [ -e "$file" ] || continue
    printf '\n%s\n' "$(basename "$file")"
    uv run python - "$file" <<'PY'
import json, sys
data = json.loads(open(sys.argv[1], encoding="utf-8").read())
total = data["summary"]["всего"]
made = data["summary"].get("чем сделано", {})
print("   модель:", made.get("модель ответа", "?"), "| промпт:", made.get("промпт", "?"))
for key in ["хотя бы одна формула", "формулы дошли", "опора на контекст",
            "размышление вместо ответа", "ответ не по-русски", "отказов"]:
    if key in total:
        print(f"   {key:<26} {total[key]}")
PY
done

cat <<'NOTE'

    КАК ЧИТАТЬ.

    Главная величина — «хотя бы одна формула». Ради неё всё и затевалось:
    для продукта про математическую литературу это самое тяжёлое
    из измеренного.

    Критерий отказа гипотезы B2 назван заранее: если после починки промпта
    крупная модель не даёт прироста, дело было в формулировке, а не
    в размере, и платить за карту побольше незачем.

    Обязательно посмотреть задержку. 30B в четырёх битах на 3090 будет
    заметно медленнее 4B, и для продукта это может перевесить прирост.

    Числа пересчитываются офлайн: scripts/recompute_answers.py — так все
    ячейки меряются одной версией измерителя, а он чинился трижды.
NOTE
